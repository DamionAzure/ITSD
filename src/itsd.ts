// .itsd = Markdown + optional frontmatter. Slides split by a line of `---`
// (ignored inside code fences). A slide may start with <!-- key: value; key: value -->.
import { marked } from "marked";
import { parseSoundSpec, type Vary } from "./sound";
import type { TraceData } from "./ctx";

export interface Slide {
  src: string; line: number; id: number; opts: Record<string, string>;
  virtual?: boolean; trace?: TraceData; // virtual slides are generated by running code
}
export interface Source { lang: string; text: string }
export interface Deck { meta: Record<string, string>; slides: Slide[]; sources: Record<string, Source>; inputs: Record<string, string>; macros: Record<string, string[]>; scripts: Record<string, string> }

/** `::: input name "Label" default="1, 2" run=blockid live` (one line, no closing `:::`). */
export interface InputDef { name: string; label: string; def: string; placeholder: string; run?: string; live: boolean }
export function parseInput(rest: string): InputDef | null {
  const m = rest.trim().match(/^([A-Za-z_]\w*)\s*(.*)$/);
  if (!m) return null;
  const a: Record<string, string> = {};
  const tail = m[2].replace(/(\w+)=("([^"]*)"|\S+)/g, (_, k, v, q) => { a[k] = q ?? v; return " "; });
  return {
    name: m[1], label: tail.match(/"([^"]*)"/)?.[1] ?? m[1], def: a.default ?? "", placeholder: a.placeholder ?? "",
    run: a.run, live: /\blive\b/.test(tail.replace(/"[^"]*"/g, "")),
  };
}
/** Every `::: input` or `::: var` line on a slide (a var is an input without a box: a named value buttons can change), skipping fenced code so documentation examples don't count. */
export function scanInputs(src: string): { line: number; def: InputDef }[] {
  const out: { line: number; def: InputDef }[] = []; let fence: string | null = null;
  src.split("\n").forEach((l, i) => {
    const f = l.match(/^\s*(`{3,}|~{3,})/);
    if (f) { fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0]; return; }
    const m = !fence && l.match(/^:::\s*(?:input|var)\s+(.*)$/);
    const def = m ? parseInput(m[1]) : null;
    if (def) out.push({ line: i, def });
  });
  return out;
}

/** "2s", "1.5s", "500ms", "2m" or a bare number of seconds -> milliseconds (null if it isn't one). */
export function parseDelay(s: string): number | null {
  const m = s.trim().match(/^(\d+(?:\.\d+)?)(ms|s|m)?$/);
  return m ? Math.round(parseFloat(m[1]) * (m[2] === "ms" ? 1 : m[2] === "m" ? 60000 : 1000)) : null;
}
/** `::: after 3s` / `::: every 1s` followed by action lines up to `:::`: a timer that starts when the slide appears (while presenting) and stops when it is left. */
export interface TimerBlock { line: number; kind: "after" | "every"; ms: number; acts: Act[] }
export function scanTimers(src: string): TimerBlock[] {
  const out: TimerBlock[] = [], lines = src.split("\n"); let fence: string | null = null;
  for (let i = 0; i < lines.length; i++) {
    const f = lines[i].match(/^\s*(`{3,}|~{3,})/);
    if (f) { fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0]; continue; }
    const m = !fence && lines[i].match(/^:::\s*(after|every)\s+(\S+)\s*$/);
    if (!m) continue;
    const ms = parseDelay(m[2]), t: TimerBlock = { line: i, kind: m[1] as "after", ms: ms === null ? -1 : m[1] === "every" ? Math.max(ms, 50) : ms, acts: [] };
    for (i++; i < lines.length && !/^:::\s*$/.test(lines[i]); i++) { const a = parseAct(lines[i].trim()); if (a) t.acts.push(a); }
    if (ms !== null) out.push(t);
  }
  return out;
}

/** A key name as written in `::: key x` -> the KeyboardEvent.key (lower case) it matches, or null. Space, the left/right arrows, PageUp/PageDown and Escape already move through the deck. */
export function parseKey(s: string): string | null {
  const k = s.trim().toLowerCase();
  const names: Record<string, string> = { enter: "enter", up: "arrowup", down: "arrowdown" };
  if (names[k]) return names[k];
  return /^[a-z0-9]$/.test(k) || /^[+\-=\[\],.;\/]$/.test(k) ? k : null;
}
/** `::: key a` followed by action lines up to `:::`: pressing the key while presenting runs the actions (on this slide only). */
export interface KeyBlock { line: number; key: string; acts: Act[] }
export function scanKeys(src: string): KeyBlock[] {
  const out: KeyBlock[] = [], lines = src.split("\n"); let fence: string | null = null;
  for (let i = 0; i < lines.length; i++) {
    const f = lines[i].match(/^\s*(`{3,}|~{3,})/);
    if (f) { fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0]; continue; }
    const m = !fence && lines[i].match(/^:::\s*key\s+(\S+)\s*$/);
    if (!m) continue;
    const key = parseKey(m[1]), k: KeyBlock = { line: i, key: key ?? "", acts: [] };
    for (i++; i < lines.length && !/^:::\s*$/.test(lines[i]); i++) { const a = parseAct(lines[i].trim()); if (a) k.acts.push(a); }
    if (key) out.push(k);
  }
  return out;
}

/** `::: when <condition>` followed by action lines up to `:::`: runs the actions when the condition turns true while the slide is showing. */
export interface WhenRule { line: number; cond: string; acts: Act[]; bad: { line: number; text: string }[] }
export function scanWhen(src: string): WhenRule[] {
  const out: WhenRule[] = [], lines = src.split("\n"); let fence: string | null = null;
  for (let i = 0; i < lines.length; i++) {
    const f = lines[i].match(/^\s*(`{3,}|~{3,})/);
    if (f) { fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0]; continue; }
    const m = !fence && lines[i].match(/^:::\s*when\s+(.+)$/);
    if (!m) continue;
    const rule: WhenRule = { line: i, cond: m[1].trim(), acts: [], bad: [] };
    for (i++; i < lines.length && !/^:::\s*$/.test(lines[i]); i++) {
      const t = lines[i].trim(); if (!t) continue;
      const a = parseAct(t); if (a) rule.acts.push(a); else rule.bad.push({ line: i, text: t });
    }
    out.push(rule);
  }
  return out;
}

/** "java run id=x" -> { lang: "java", flags: {run}, attrs: {id: "x"} } */
export function parseInfo(info: string) {
  const [first, ...rest] = info.trim().split(/\s+/);
  const flags = new Set<string>(); const attrs: Record<string, string> = {};
  for (const r of rest) { const m = r.match(/^(\w+)=(.*)$/); if (m) attrs[m[1]] = m[2]; else flags.add(r); }
  return { lang: first || "text", flags, attrs };
}

export function parseOpts(src: string): Record<string, string> {
  const o: Record<string, string> = {};
  const m = src.match(/^\s*<!--([\s\S]*?)-->/);
  if (m && !/^\s*@/.test(m[1])) for (const kv of m[1].split(";")) {
    const [k, ...v] = kv.split(":");
    if (v.length) o[k.trim()] = v.join(":").trim();
  }
  return o;
}

export function parseDeck(text: string): Deck {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const meta: Record<string, string> = {};
  let i = 0;
  if (lines[0]?.trim() === "---") {
    const end = lines.findIndex((l, k) => k > 0 && l.trim() === "---");
    if (end > 0) {
      for (const l of lines.slice(1, end)) {
        const m = l.match(/^(\w[\w-]*):\s*(.*)$/);
        if (m) meta[m[1]] = m[2];
      }
      i = end + 1;
    }
  }
  const slides: Slide[] = [];
  let buf: string[] = [], start = i, fence: string | null = null;
  const push = () => { const src = buf.join("\n"); slides.push({ src, line: start, id: slides.length, opts: parseOpts(src) }); };
  for (; i < lines.length; i++) {
    const l = lines[i];
    const f = l.match(/^\s*(`{3,}|~{3,})/);
    if (f) fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0];
    if (!fence && /^---\s*$/.test(l)) { push(); buf = []; start = i + 1; continue; }
    buf.push(l);
  }
  push();

  // Named inline sources: a fence tagged def=name is hidden and usable from any button.
  const sources: Record<string, Source> = {};
  for (const s of slides) for (const t of marked.lexer(s.src) as any[]) {
    if (t.type !== "code") continue;
    const { lang, attrs } = parseInfo(t.lang ?? "");
    if (attrs.def) sources[attrs.def] = { lang, text: t.text };
  }
  const inputs: Record<string, string> = {};
  for (const s of slides) for (const { def } of scanInputs(s.src)) if (!(def.name in inputs)) inputs[def.name] = def.def;
  const macros: Record<string, string[]> = {}, scripts: Record<string, string> = {};
  for (const s of slides) for (const d of scanDefs(s.src)) { if (d.kind === "macro") macros[d.name] = d.body; else scripts[d.name] = d.body.join("\n"); }
  return { meta, slides, sources, inputs, macros, scripts };
}

/** `::: macro name` (action lines, `$1` `$2` `$*` for the arguments of `call name ...`) and `::: script name` (JavaScript, see script.ts), each closed by a `:::` line.
 *  Defined on any slide, usable from every slide. */
export interface Def { line: number; kind: "macro" | "script"; name: string; body: string[] }
export function scanDefs(src: string): Def[] {
  const out: Def[] = [], lines = src.split("\n"); let fence: string | null = null;
  for (let i = 0; i < lines.length; i++) {
    const f = lines[i].match(/^\s*(`{3,}|~{3,})/);
    if (f) { fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0]; continue; }
    const m = !fence && lines[i].match(/^:::\s*(macro|script)\s+([A-Za-z_]\w*)\s*$/);
    if (!m) continue;
    const d: Def = { line: i, kind: m[1] as "macro", name: m[2], body: [] };
    for (i++; i < lines.length && !/^:::\s*$/.test(lines[i]); i++) d.body.push(lines[i]);
    out.push(d);
  }
  return out;
}

/** `::: on enter [once]` / `::: on leave` / `::: on key r space` / `::: on change score`, then action lines up to `:::`.
 *  enter / leave fire as the slide appears / goes (while presenting); key fires on those keys while the slide is up; change fires when that variable changes. */
export interface OnRule { line: number; event: "enter" | "leave" | "key" | "change"; arg: string; once: boolean; acts: Act[]; bad: { line: number; text: string }[] }
export function scanOn(src: string): OnRule[] {
  const out: OnRule[] = [], lines = src.split("\n"); let fence: string | null = null;
  for (let i = 0; i < lines.length; i++) {
    const f = lines[i].match(/^\s*(`{3,}|~{3,})/);
    if (f) { fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0]; continue; }
    const m = !fence && lines[i].match(/^:::\s*on\s+(enter|leave|key|change)(?:\s+(.*))?$/);
    if (!m) continue;
    const arg = (m[2] ?? "").trim(), rule: OnRule = { line: i, event: m[1] as "enter", arg: arg.replace(/\bonce\b/, "").trim(), once: /\bonce\b/.test(arg), acts: [], bad: [] };
    for (i++; i < lines.length && !/^:::\s*$/.test(lines[i]); i++) {
      const t = lines[i].trim(); if (!t) continue;
      const a = parseAct(t); if (a) rule.acts.push(a); else rule.bad.push({ line: i, text: t });
    }
    out.push(rule);
  }
  return out;
}

export type Act =
  | { op: "set"; id: string; ref: string; as?: string }
  | { op: "run" | "show" | "hide" | "start" | "stop"; id: string }
  | { op: "goto"; n: number }
  | { op: "play"; name: string; vol?: Vary; pitch?: Vary } // `play boom vol=0.8 pitch=1+-0.2` (see sound.ts)
  | { op: "add"; name: string; v: string } | { op: "sub"; name: string; v: string } | { op: "put"; name: string; v: string; calc?: boolean } // change a deck variable (see `::: var`)
  | { op: "branch"; n: number } | { op: "proceed" } | { op: "back" } // branch slides (see branch.ts)
  | { op: "after"; ms: number; act: Act } | { op: "every"; ms: number; act: Act } | { op: "cancel" } // timers (see SlideView)
  | { op: "wait"; ms: number } // pause the actions that follow it in the same list
  | { op: "if"; cond: string; then: Act; else?: Act } | { op: "repeat"; n: number; act: Act }
  | { op: "toggle"; name: string } | { op: "reset"; name?: string } | { op: "random"; name: string; lo: string; hi: string }
  | { op: "call"; name: string; args: string[] } | { op: "script"; name: string; args: string[] }; // a ::: macro / ::: script

export function parseAct(line: string): Act | null {
  const t = line.trim(); let m;
  if ((m = t.match(/^set\s+(\S+)\s*=\s*(.+?)(?:\s+as\s+(\S+))?$/))) return { op: "set", id: m[1], ref: m[2].replace(/^["']|["']$/g, ""), as: m[3] };
  if ((m = t.match(/^(run|show|hide|start|stop)\s+(\S+)$/))) return { op: m[1] as "run", id: m[2] };
  if ((m = t.match(/^goto\s+(\d+)$/))) return { op: "goto", n: +m[1] };
  if ((m = t.match(/^play\s+(.+)$/))) { const sp = parseSoundSpec(m[1]); return sp ? { op: "play", ...sp } : null; }
  // add / sub take a number or a calculation (`add score bonus * 2`); `put name = <calculation>` calculates, `put name text` stores the text as written
  if ((m = t.match(/^(add|sub)\s+([A-Za-z_]\w*)\s+(.+)$/))) return { op: m[1], name: m[2], v: m[3].trim() } as Act;
  if ((m = t.match(/^put\s+([A-Za-z_]\w*)\s*=\s*(.+)$/))) return { op: "put", name: m[1], v: m[2].trim(), calc: true };
  if ((m = t.match(/^put\s+([A-Za-z_]\w*)\s+(.+)$/))) return { op: "put", name: m[1], v: m[2].replace(/^["']|["']$/g, "") };
  if ((m = t.match(/^(after|every)\s+(\S+)\s+(.+)$/))) { // `after 2s show answer`, `every 1s sub time 1`
    const ms = parseDelay(m[2]), act = ms === null ? null : parseAct(m[3]);
    return ms !== null && act ? ({ op: m[1], ms: m[1] === "every" ? Math.max(ms, 50) : ms, act } as Act) : null;
  }
  if (t === "cancel") return { op: "cancel" };
  if ((m = t.match(/^wait\s+(\S+)$/))) { const ms = parseDelay(m[1]); return ms === null ? null : { op: "wait", ms }; }
  if ((m = t.match(/^if\s+(.+?)\s+then\s+(.+?)(?:\s+else\s+(.+))?$/))) { // `if score >= 5 then goto 3 else play error`
    const th = parseAct(m[2]), el = m[3] ? parseAct(m[3]) : undefined;
    return th && el !== null ? { op: "if", cond: m[1].trim(), then: th, ...(el ? { else: el } : null) } : null;
  }
  if ((m = t.match(/^repeat\s+(\d+)\s+(.+)$/))) { const a = parseAct(m[2]); return a && +m[1] >= 1 && +m[1] <= 1000 ? { op: "repeat", n: +m[1], act: a } : null; }
  if ((m = t.match(/^toggle\s+([A-Za-z_]\w*)$/))) return { op: "toggle", name: m[1] };
  if ((m = t.match(/^random\s+([A-Za-z_]\w*)\s+(\S+)\s+(\S+)$/))) return { op: "random", name: m[1], lo: m[2], hi: m[3] }; // `random roll 1 6`
  if ((m = t.match(/^(call|script)\s+([A-Za-z_]\w*)(?:\s+(.*))?$/))) return { op: m[1] as "call", name: m[2], args: m[3] ? [...m[3].matchAll(/"([^"]*)"|\S+/g)].map((x) => x[1] ?? x[0]) : [] };
  if ((m = t.match(/^reset(?:\s+([A-Za-z_]\w*))?$/))) return { op: "reset", name: m[1] };
  if ((m = t.match(/^branch\s+(\d+)$/))) return { op: "branch", n: +m[1] };
  if (/^(proceed|back)$/.test(t)) return { op: t === "back" ? "back" : "proceed" };
  return null;
}
