// .itsd = Markdown + optional frontmatter. Slides split by a line of `---`
// (ignored inside code fences). A slide may start with <!-- key: value; key: value -->.
import { marked } from "marked";
import type { TraceData } from "./ctx";

export interface Slide {
  src: string; line: number; id: number; opts: Record<string, string>;
  virtual?: boolean; trace?: TraceData; // virtual slides are generated by running code
}
export interface Source { lang: string; text: string }
export interface Deck { meta: Record<string, string>; slides: Slide[]; sources: Record<string, Source>; inputs: Record<string, string> }

/** `::: input name "Label" default="1, 2" run=blockid live` (one line, no closing `:::`). */
export interface InputDef { name: string; label: string; def: string; placeholder: string; run?: string; live: boolean }
export function parseInput(rest: string): InputDef | null {
  const m = rest.trim().match(/^([A-Za-z_]\w*)\s*(.*)$/);
  if (!m) return null;
  const a: Record<string, string> = {};
  const tail = m[2].replace(/(\w+)=("([^"]*)"|\S+)/g, (_, k, v, q) => { a[k] = q ?? v; return " "; });
  return {
    name: m[1], label: tail.match(/"([^"]*)"/)?.[1] ?? m[1], def: a.default ?? "", placeholder: a.placeholder ?? "",
    run: a.run, live: /\blive\b/.test(tail.replace(/"[^"]*"/g, "")),
  };
}
/** Every input line on a slide, skipping fenced code so documentation examples don't count. */
export function scanInputs(src: string): { line: number; def: InputDef }[] {
  const out: { line: number; def: InputDef }[] = []; let fence: string | null = null;
  src.split("\n").forEach((l, i) => {
    const f = l.match(/^\s*(`{3,}|~{3,})/);
    if (f) { fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0]; return; }
    const m = !fence && l.match(/^:::\s*input\s+(.*)$/);
    const def = m ? parseInput(m[1]) : null;
    if (def) out.push({ line: i, def });
  });
  return out;
}

/** "java run id=x" -> { lang: "java", flags: {run}, attrs: {id: "x"} } */
export function parseInfo(info: string) {
  const [first, ...rest] = info.trim().split(/\s+/);
  const flags = new Set<string>(); const attrs: Record<string, string> = {};
  for (const r of rest) { const m = r.match(/^(\w+)=(.*)$/); if (m) attrs[m[1]] = m[2]; else flags.add(r); }
  return { lang: first || "text", flags, attrs };
}

export function parseOpts(src: string): Record<string, string> {
  const o: Record<string, string> = {};
  const m = src.match(/^\s*<!--([\s\S]*?)-->/);
  if (m && !/^\s*@/.test(m[1])) for (const kv of m[1].split(";")) {
    const [k, ...v] = kv.split(":");
    if (v.length) o[k.trim()] = v.join(":").trim();
  }
  return o;
}

export function parseDeck(text: string): Deck {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const meta: Record<string, string> = {};
  let i = 0;
  if (lines[0]?.trim() === "---") {
    const end = lines.findIndex((l, k) => k > 0 && l.trim() === "---");
    if (end > 0) {
      for (const l of lines.slice(1, end)) {
        const m = l.match(/^(\w[\w-]*):\s*(.*)$/);
        if (m) meta[m[1]] = m[2];
      }
      i = end + 1;
    }
  }
  const slides: Slide[] = [];
  let buf: string[] = [], start = i, fence: string | null = null;
  const push = () => { const src = buf.join("\n"); slides.push({ src, line: start, id: slides.length, opts: parseOpts(src) }); };
  for (; i < lines.length; i++) {
    const l = lines[i];
    const f = l.match(/^\s*(`{3,}|~{3,})/);
    if (f) fence = fence ? (f[1][0] === fence ? null : fence) : f[1][0];
    if (!fence && /^---\s*$/.test(l)) { push(); buf = []; start = i + 1; continue; }
    buf.push(l);
  }
  push();

  // Named inline sources: a fence tagged def=name is hidden and usable from any button.
  const sources: Record<string, Source> = {};
  for (const s of slides) for (const t of marked.lexer(s.src) as any[]) {
    if (t.type !== "code") continue;
    const { lang, attrs } = parseInfo(t.lang ?? "");
    if (attrs.def) sources[attrs.def] = { lang, text: t.text };
  }
  const inputs: Record<string, string> = {};
  for (const s of slides) for (const { def } of scanInputs(s.src)) if (!(def.name in inputs)) inputs[def.name] = def.def;
  return { meta, slides, sources, inputs };
}

export type Act =
  | { op: "set"; id: string; ref: string; as?: string }
  | { op: "run" | "show" | "hide" | "start" | "stop"; id: string }
  | { op: "goto"; n: number };

export function parseAct(line: string): Act | null {
  const t = line.trim(); let m;
  if ((m = t.match(/^set\s+(\S+)\s*=\s*(.+?)(?:\s+as\s+(\S+))?$/))) return { op: "set", id: m[1], ref: m[2].replace(/^["']|["']$/g, ""), as: m[3] };
  if ((m = t.match(/^(run|show|hide|start|stop)\s+(\S+)$/))) return { op: m[1] as "run", id: m[2] };
  if ((m = t.match(/^goto\s+(\d+)$/))) return { op: "goto", n: +m[1] };
  return null;
}
